import { test, expect } from '@playwright/test';
test('mobile interface, challenges, and empty journal', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/');
  await expect(page.getByRole('heading', { name: 'Hello, fellow birdwatcher.' })).toBeVisible();
  await page.screenshot({ path: 'screenshots/mobile.png', fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.goto('/#challenges');
  await page.getByRole('button', { name: 'Mark complete' }).first().click();
  await expect(page.getByRole('button', { name: 'Completed', exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByRole('button', { name: 'Completed', exact: true })).toBeVisible();
  await page.goto('/#discoveries');
  await expect(page.getByRole('heading', { name: 'Your story starts with a bird.' })).toBeVisible();
});
test('real ONNX inference, save, and offline identification', async ({ page, context }) => {
  await page.goto('/#identify');
  await page.locator('input[type=file]').first().setInputFiles('tests/fixtures/abbotts-babbler.jpg');
  await expect(page.getByRole('heading', { name: 'Abbotts Babbler', exact: true })).toBeVisible({ timeout: 150_000 });
  const score = await page.locator('.score strong').textContent();
  console.log('Actual test-image model score:', score);
  await expect(page.getByText('The model cannot confidently identify this bird.', { exact: false })).toBeVisible();
  await expect(page.getByText('Malacocincla abbotti', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Save this discovery' }).click();
  await expect(page.getByRole('button', { name: 'Saved to your discoveries' })).toBeVisible();
  await page.evaluate(async () => { await navigator.serviceWorker.ready; });
  await context.setOffline(true);
  await page.reload();
  await page.goto('/#discoveries');
  await expect(page.getByRole('heading', { name: 'Abbotts Babbler', exact: true })).toBeVisible();
  await page.getByRole('textbox', { name: 'Search discoveries by species' }).fill('no matching species');
  await expect(page.getByRole('heading', { name: 'No matching discoveries' })).toBeVisible();
  await page.getByRole('button', { name: 'Clear filters' }).click();
  await page.goto('/#identify');
  await page.locator('input[type=file]').first().setInputFiles('tests/fixtures/abbotts-babbler.jpg');
  await expect(page.getByRole('heading', { name: 'Abbotts Babbler', exact: true })).toBeVisible({ timeout: 150_000 });
  await context.setOffline(false);
  await page.goto('/');
  await page.screenshot({ path: 'screenshots/dashboard.png', fullPage: true });
  await page.goto('/#discoveries');
  await page.getByRole('button', { name: 'View Abbotts Babbler' }).click();
  await page.screenshot({ path: 'screenshots/result.png', fullPage: true });
  page.once('dialog', dialog => dialog.accept());
  await page.goto('/#discoveries');
  await page.getByRole('button', { name: 'Remove Abbotts Babbler' }).click();
  await expect(page.getByRole('heading', { name: 'Your story starts with a bird.' })).toBeVisible();
});
